//! A shared store of `node_modules`, keyed by the lockfile's hash: a new workspace whose lockfile
//! matches main gets a copy-on-write clone (`cp -c`, near-free on APFS) instead of a fresh install.
//! Same layout as the previous core (`nm-store/<repo>/<hash>/node_modules`).

use std::path::{Path, PathBuf};
use std::process::Command;

use pom_paths::StateDir;
use sha2::{Digest, Sha256};

const LOCKFILES: [&str; 2] = ["yarn.lock", "package-lock.json"];

pub fn lock_hash(worktree: &Path) -> Option<String> {
    LOCKFILES.iter().find_map(|name| {
        let bytes = std::fs::read(worktree.join(name)).ok()?;
        let digest = Sha256::digest(&bytes);
        Some(
            digest
                .iter()
                .take(8)
                .map(|byte| format!("{byte:02x}"))
                .collect(),
        )
    })
}

fn store_dir(state: &StateDir, repo: &str, hash: &str) -> PathBuf {
    state
        .path("nm-store")
        .join(repo)
        .join(hash)
        .join("node_modules")
}

/// Clones the store copy into the worktree (filling the store from main first when main's lockfile
/// matches). Returns whether `node_modules` came from the store.
pub fn restore(state: &StateDir, repo: &str, worktree: &Path, main: &Path) -> bool {
    let target = worktree.join("node_modules");
    if target.exists() {
        return false;
    }
    let Some(hash) = lock_hash(worktree) else {
        return false;
    };
    let store = store_dir(state, repo, &hash);
    if !store.is_dir() {
        let main_modules = main.join("node_modules");
        if lock_hash(main) != Some(hash) || !main_modules.is_dir() {
            return false;
        }
        if clone_tree(&main_modules, &store).is_err() {
            return false;
        }
    }
    clone_tree(&store, &target).is_ok()
}

/// Keeps a freshly installed `node_modules` for the next workspace with the same lockfile.
pub fn snapshot(state: &StateDir, repo: &str, worktree: &Path) {
    let source = worktree.join("node_modules");
    let Some(hash) = lock_hash(worktree).filter(|_| source.is_dir()) else {
        return;
    };
    let store = store_dir(state, repo, &hash);
    if store.is_dir() {
        return;
    }
    if let Err(error) = clone_tree(&source, &store) {
        eprintln!("workspace: snapshot node_modules for {repo}: {error}");
    }
}

fn clone_tree(source: &Path, target: &Path) -> std::io::Result<()> {
    if target.exists() {
        std::fs::remove_dir_all(target)?;
    }
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let cloned = Command::new("cp")
        .arg("-c")
        .arg("-R")
        .arg(source)
        .arg(target)
        .status()?;
    if cloned.success() {
        return Ok(());
    }
    if target.exists() {
        std::fs::remove_dir_all(target)?;
    }
    let copied = Command::new("cp")
        .arg("-R")
        .arg(source)
        .arg(target)
        .status()?;
    if copied.success() {
        Ok(())
    } else {
        Err(std::io::Error::other(format!(
            "cp {} failed",
            source.display()
        )))
    }
}
